    class AuthorityServiceHandler(win32serviceutil.ServiceFramework):
        """Actual Windows Service handler for audit authority.
        
        F14 V4-r9 FIX: Service framework for running authority as Windows Service.
        
        This class is a subclass of win32serviceutil.ServiceFramework and
        implements the service lifecycle (start, stop, SvcDoRun).
        
        To use this as a real service, it must be registered with
        Windows Service Control Manager via service installation.
        """
        
        _svc_name_ = "IABVAuditAuthority"
        _svc_display_name_ = "IABV Audit Authority Service"
        _svc_description_ = "Cryptographic audit authority for IABV provenance verification"
        
        def __init__(self, args):
            win32serviceutil.ServiceFramework.__init__(self, args)
            self.hWaitStop = win32event.CreateEvent(None, 0, 0, None)
            logger.info("AuthorityServiceHandler initialized")
        
        def SvcStop(self):
            """Handle service stop."""
            self.ReportServiceStatus(win32service.SERVICE_STOP_PENDING)
            win32event.SetEvent(self.hWaitStop)
            logger.info("AuthorityServiceHandler stopping")
        
        def SvcDoRun(self):
            """Main service loop.
            
            F14 V4-r9.4 FIX: Load authority key, verify identity, start IPC.
            Provisioning controlled by AUTHORITY_PROVISIONING_ENABLED flag file in C:\ProgramData\IABV\.
            Only Administrators can create this flag file, preventing normal users from enabling provisioning.
            """
            logger.info("AuthorityServiceHandler running")
            servicemanager.LogMsg(
                servicemanager.EVENTLOG_INFORMATION,
                servicemanager.PYS_SERVICE_STARTED,
                (self._svc_name_, "")
            )
            
            # F14 V4-r9.4 FIX: Initialize key manager
            key_manager = None
            pipe_server = None
            
            try:
                # Step 1: Initialize key manager
                key_storage_path = Path("C:\\ProgramData\\IABV\\authority_keys")
                program_data_path = Path("C:\\ProgramData\\IABV")
                key_manager = AuthorityKeyManager(
                    key_storage_path=key_storage_path,
                    service_identity="LocalService",
                    program_data_path=program_data_path
                )
                logger.info("Key manager initialized")
                
                # Step 2: Load authority key (fail-closed if missing unless provisioning flag exists)
                try:
                    key_manager.load_key()
                    logger.info("Authority key loaded successfully")
                except AuthorityKeyError as exc:
                    logger.error("Failed to load authority key: %s", exc)
                    logger.error("Service cannot operate without a valid key. Provisioning must create the key first.")
                    logger.error("To enable provisioning, create AUTHORITY_PROVISIONING_ENABLED flag in C:\\ProgramData\\IABV\\ as Administrator.")
                    self.ReportServiceStatus(win32service.SERVICE_STOPPED, win32service.ERROR_SERVICE_SPECIFIC_ERROR)
                    return
                
                # Step 3: Create Named Pipe server with key manager
                pipe_server = AuthorityNamedPipeServer(
                    pipe_name=r"\\.\pipe\IABVAuditAuthority",
                    authorized_sids=None,  # Will auto-detect during installation
                    key_manager=key_manager
                )
                pipe_server.start()
                logger.info("Named Pipe server started with authority key")
                
                # Step 4: Report service as ready
                self.ReportServiceStatus(win32service.SERVICE_RUNNING)
                logger.info("Authority service ready")
                
                # Step 5: Wait for stop signal
                win32event.WaitForSingleObject(self.hWaitStop, win32event.INFINITE)
                
            except Exception as exc:
                logger.error("Service main loop error: %s", exc)
                self.ReportServiceStatus(win32service.SERVICE_STOPPED, win32service.ERROR_SERVICE_SPECIFIC_ERROR)
            finally:
                # Stop Named Pipe server
                if pipe_server:
                    pipe_server.stop()
                    logger.info("Named Pipe server stopped")
            
            logger.info("AuthorityServiceHandler stopped")


